package dev.mcmateriallist.core.stock;

import dev.mcmateriallist.core.location.ContainerPosition;
import dev.mcmateriallist.core.location.LocationLimits;
import java.util.List;
import java.util.Map;
import java.util.Objects;

/**
 * Live world access, implemented by fabric on the server thread. StockScan calls it only for authorized positions, at most once
 * per container step; it must never load a chunk.
 */
public interface ContainerProbe {
    /** The registered position's live shape. Unloaded when its chunk is not loaded; nothing else may be inspected then. */
    Shape shape(String dimension, ContainerPosition registered);
    /** Contents of one unit whose shape was resolved in the same step: one position, or both halves of a double chest. */
    Reading read(String dimension, List<ContainerPosition> halves);

    sealed interface Shape permits Unloaded, Present {}
    record Unloaded() implements Shape {}
    /**
     * blockId is the live block. partner is the other half of a double chest that points back at this one (with this block's id),
     * or null for a single container; partnerLoaded=false means the block claims a partner whose chunk is not loaded.
     */
    record Present(String blockId, ContainerPosition partner, boolean partnerLoaded) implements Shape {
        public Present { if (!LocationLimits.namespacedId(blockId)) throw new IllegalArgumentException("Invalid block id"); }
        public static Present single(String blockId) { return new Present(blockId, null, false); }
    }
    sealed interface Reading permits Contents, Unreadable {}
    /** Raw item id to count; StockScan validates the bounds and reports UNREADABLE when they do not hold. */
    record Contents(Map<String, Long> counts) implements Reading {
        public Contents { counts = Map.copyOf(Objects.requireNonNull(counts, "counts")); }
    }
    /** No block entity, an ungenerated loot table (never generated by reading), or an unsupported inventory. */
    record Unreadable() implements Reading {}
}
